"""four_fronts_gen.py: the settling recursion of CL730/CL733 on the four strips of L1513, in Python, and the kernel modules
that let Lean check it (CL734). Reads A0, A1, B0, B1 from the four-left-sides kit module, builds each strip's sixteen rows
and its sixteen-bit words, runs the phase-0 recursion F(0) = 0, F(1) = 1, F(j+2) = max(F j, F (j+1)) + (0 if wheel j+1 is
white, else 1 + the wait to its first black at or after that max), and writes one Lean module per strip: the sixteen rows as
literals, and the recursion's state at every 5,000 wheels as `frun` equations for `decide +kernel`. The pairs it prints are
the predictions the kernel then confirms or refutes (the replay in a second language is by construction).
Usage: python3 four_fronts_gen.py [OUTDIR]   (no OUTDIR: print only)."""
import re, sys, time
K = 87867; MASK = (1 << K) - 1; P = 16; CH = 5000; JMAX = 87866
SRC = 'reports/wolfram-agents/submissions/four-left-sides/Rule30FourLeftSides.lean'
src = open(SRC).read()
def step(v): return ((v << 2) ^ ((v << 1) | v)) & MASK
def literal(name):
    m = re.search(r'^def %s : Nat := (.*?)$' % name, src, re.M); body = m.group(1)
    h = int(re.findall(r'0x[0-9a-fA-F]+', body)[0], 16); sh = re.search(r'<<<\s*(\d+)', body)
    return h << int(sh.group(1)) if sh else h
A0 = literal('A0'); A1 = A0 ^ literal('A1'); B0 = A0 ^ literal('B0'); B1 = B0 ^ literal('B1')
strips = [('A0', A0), ('A1', A1), ('B0', B0), ('B1', B1)]
def rows_of(v):
    rows = [v]
    for _ in range(P): rows.append(step(rows[-1]))
    assert rows[P] == v, "no 16-tick return"
    return rows[:P]
def words_of(rows):
    return [sum(((rows[r] >> j) & 1) << r for r in range(P)) for j in range(K)]
def srch(w, m):
    for r in range(P):
        if (w >> ((m + r) % P)) & 1: return r
    return P
def fstep(w, j, st):
    a, b = st; m = max(a, b)
    return (b, m) if w[j + 1] == 0 else (b, m + srch(w[j + 1], m) + 1)
expected = {'A0': 176968, 'A1': 177229, 'B0': 177170, 'B1': 177560}   # CL733 part A, forced_front4.py
bounds = list(range(0, JMAX, CH)) + [JMAX]
outdir = sys.argv[1] if len(sys.argv) > 1 else None
t0 = time.time(); allok = True
for name, v in strips:
    rows = rows_of(v); w = words_of(rows)
    whites = [j for j in range(K) if w[j] == 0]
    st = (0, 1); states = {0: st}
    for j in range(JMAX):
        st = fstep(w, j, st)
        if j + 1 in bounds: states[j + 1] = st
    F87866 = states[JMAX][0]; ok = F87866 == expected[name]; allok &= ok
    st2 = (0, 1)   # F(53207) is not a block boundary; recomputed for the record (part C's number on the B strip is 107,310)
    for j in range(53207): st2 = fstep(w, j, st2)
    print(f"{name}: white wheels {whites}; F(53207) = {st2[0]}; F(87866) = {F87866} (CL733: {expected[name]}, {'agree' if ok else 'DIFFER'})")
    chunks = [(bounds[i], bounds[i + 1] - bounds[i], states[bounds[i]], states[bounds[i + 1]]) for i in range(len(bounds) - 1)]
    for (j0, n, s0, s1) in chunks: print(f"  frun wd {j0} {n} {s0} = {s1}")
    if outdir:
        L = []
        L.append("module\n\npublic import Ruliology.CellularAutomata.Rule30FourFrontsBase\n")
        L.append(f"/-!\n# The strip `{name}` of `Rule30FourLeftSides`: its sixteen rows, and the settling recursion through wheel 87,866 by the kernel\n\n"
                 f"The sixteen rows of `{name}`'s cycle as literals, each checked against `rowAt 87867 {name} r`; the sixteen-bit word `wd j` of each wheel;\n"
                 f"and the recursion of `Rule30FourFrontsBase` evaluated by `decide +kernel` in blocks of {CH:,} wheels (`chunk0` … `chunk{len(chunks)-1}`).\n"
                 f"The pairs in the statements are `(F j, F (j + 1))` at the block boundaries, computed in Python first; the kernel confirms them.\n"
                 f"Generated by the contributors' `four_fronts_gen.py` (Cloud, CL734).\n-/\n\n@[expose] public section\n\n"
                 f"namespace Ruliology.CellularAutomata.Rule30FourFronts{name}\n\n"
                 f"open Rule30FourFrontsBase (word16 frun)\nopen Rule30UniversalLeftSide (rowAt)\nopen Rule30FourLeftSides ({name})\n\n"
                 f"set_option autoImplicit false\nset_option maxRecDepth 400000\n\n/-! ### The sixteen rows -/\n")
        for r in range(P): L.append(f"def R{r} : Nat := 0x{rows[r]:x}\n")
        L.append("\n/-- The rows of the cycle, by phase. -/\ndef R : Nat → Nat\n" + "".join(f"  | {r} => R{r}\n" for r in range(P)) + "  | _ => 0\n\n")
        for r in range(P): L.append(f"theorem R_eq_{r} : R {r} = rowAt 87867 {name} {r} := by decide +kernel\n")
        L.append(f"\ntheorem R_eq : ∀ r, r < 16 → R r = rowAt 87867 {name} r\n" + "".join(f"  | {r}, _ => R_eq_{r}\n" for r in range(P)) + "  | n + 16, h => absurd h (by omega)\n\n")
        L.append(f"/-- The sixteen-bit word of wheel `j`: bit `r` is wheel `j` of row `r`. -/\ndef wd (j : Nat) : Nat := word16 (fun r => (R r).testBit j)\n\n/-! ### The recursion, in blocks -/\n\n")
        for i, (j0, n, s0, s1) in enumerate(chunks):
            L.append(f"theorem chunk{i} : frun wd {j0} {n} ({s0[0]}, {s0[1]}) = ({s1[0]}, {s1[1]}) := by decide +kernel\n")
        L.append(f"\nend Ruliology.CellularAutomata.Rule30FourFronts{name}\n")
        open(f"{outdir}/Rule30FourFronts{name}.lean", 'w').write("".join(L))
print(f"all four F(87866) agree with CL733: {allok}; {time.time()-t0:.1f} s")
