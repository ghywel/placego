# ---- helpers ---------------------------------------------------------------------------------------------------------

def snapshot_pair(kits, out):
    seen = {}
    roots = [os.path.join(kit, tree) for kit in kits for tree in H.BUILD_TREES] + [out]
    for root in roots:
        for r, _, files in os.walk(root):
            for f in files:
                p = os.path.join(r, f)
                try: seen[p] = os.path.getsize(p)
                except OSError: pass
    return seen


def new_artifact_bytes_pair(kits, out, baseline):
    total = 0
    for p, size in snapshot_pair(kits, out).items():
        if p not in baseline or size > baseline[p]:
            total += size - baseline.get(p, 0)
    return total


def parse_groups(text, pgids):
    """Per-pgid (rss bytes, cpu seconds, members, lean processes) from ONE ps listing; groups absent in it give zeros."""
    want = {str(p): [0, 0.0, 0, 0] for p in pgids}
    for line in text.splitlines():
        parts = line.split(None, 3)
        if len(parts) < 4 or parts[0] not in want:
            continue
        w = want[parts[0]]
        w[0] += int(parts[1]) * 1024; w[2] += 1
        secs = 0.0
        for piece in parts[2].split(':'):
            secs = secs * 60 + float(piece)
        w[1] += secs
        if os.path.basename(parts[3].strip()) == 'lean':
            w[3] += 1
    return {int(k): tuple(v) for k, v in want.items()}


def groups_sample(pgids, sample_no=0):
    """One checked ps listing for all owned groups; returns (sample time, {pgid: (rss, cpu, members, lean)})."""
    if H.FAULTS['ps_fail_after'] is not None and sample_no >= H.FAULTS['ps_fail_after']:
        raise H.MonitorError('injected ps failure')
    t = time.monotonic()
    PS_READS[0] += 1
    return t, parse_groups(H.checked(['ps', '-axo', 'pgid=,rss=,time=,comm=']), pgids)


def module_matcher(W, K, n):
    def m(rc, text):
        if rc == 0 and 'error' not in text:
            return 'pass', 'built'
        mm = re.search(r'check %d (\d+) %d (\d+) = true' % (W, n), text)
        if mm and rejected_as_false(text, 'check %d %s %d %s = true' % (W, mm.group(1), n, mm.group(2))):
            return 'FAIL', 'rejected-as-false: chunk %s at K = %s (not a proof of the negation)' % (mm.group(2), mm.group(1))
        return 'FAIL', 'build error (exit %d)' % rc
    return m


def m_rc0(rc, text):
    return ('pass' if rc == 0 else 'FAIL', 'exit %d' % rc)


def m_raise(rc, text):
    raise RuntimeError('injected matcher failure')


def hardware():
    keys = ['machdep.cpu.brand_string', 'hw.perflevel0.physicalcpu', 'hw.perflevel1.physicalcpu', 'hw.ncpu', 'hw.memsize']
    hw = {}
    for k in keys:
        r = subprocess.run(['sysctl', '-n', k], capture_output=True, text=True)
        hw[k] = r.stdout.strip() if r.returncode == 0 else None
    hw['nice_inherited'] = os.nice(0)
    return hw


def pair_verdict(pair, recs):
    """The pair's terminal verdict from its own reason and problems and the children's CURRENT verdicts; called again
    after output validation so a child downgraded to FAIL (missing-output) propagates into the stored pair verdict."""
    verdicts = [r['verdict'] for r in recs]
    if pair['reason'] != 'completed' or pair['final_problems'] or 'UNKNOWN' in verdicts or 'incomplete' in verdicts:
        pair['verdict'] = 'UNKNOWN'
    elif all(v == 'pass' for v in verdicts):
        pair['verdict'] = 'pass'
    else:
        pair['verdict'] = 'FAIL'
    return pair['verdict']


