# ---- helpers ---------------------------------------------------------------------------------------------------------

def snapshot_pair(kits, out):
    seen = {}
    for kit in kits:
        for tree in H.BUILD_TREES:
            for r, _, files in os.walk(os.path.join(kit, tree)):
                for f in files:
                    p = os.path.join(r, f)
                    try: seen[p] = os.path.getsize(p)
                    except OSError: pass
    for r, _, files in os.walk(out):
        for f in files:
            p = os.path.join(r, f)
            try: seen[p] = os.path.getsize(p)
            except OSError: pass
    return seen


def new_artifact_bytes_pair(kits, out, baseline):
    total = 0
    for p, size in snapshot_pair(kits, out).items():
        if p not in baseline or size > baseline[p]:
            total += size - baseline.get(p, 0)
    return total


def module_matcher(W, K, n):
    def m(rc, text):
        if rc == 0 and 'error' not in text:
            return 'pass', 'built'
        mm = re.search(r'check %d (\d+) %d (\d+) = true' % (W, n), text)
        if mm and rejected_as_false(text, 'check %d %s %d %s = true' % (W, mm.group(1), n, mm.group(2))):
            return 'FAIL', 'rejected-as-false: chunk %s at K = %s (not a proof of the negation)' % (mm.group(2), mm.group(1))
        return 'FAIL', 'build error (exit %d)' % rc
    return m


def m_rc0(rc, text):
    return ('pass' if rc == 0 else 'FAIL', 'exit %d' % rc)


def hardware():
    keys = ['machdep.cpu.brand_string', 'hw.perflevel0.physicalcpu', 'hw.perflevel1.physicalcpu', 'hw.ncpu', 'hw.memsize']
    hw = {}
    for k in keys:
        r = subprocess.run(['sysctl', '-n', k], capture_output=True, text=True)
        hw[k] = r.stdout.strip() if r.returncode == 0 else None
    hw['nice'] = os.nice(0)
    return hw


