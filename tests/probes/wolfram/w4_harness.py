class PairSupervisor(H.Supervisor):
    def __init__(self, kit_a, kit_b, out):
        super().__init__(kit_a, out)
        self.kits = [kit_a, kit_b]
        self.receipts['kit_b'] = kit_b
        self.pair_baseline = snapshot_pair(self.kits, out)

    def rebaseline(self):
        self.art_baseline = H.snapshot(self.kit, self.out)
        self.pair_baseline = snapshot_pair(self.kits, self.out)

    def pair_artifacts(self):
        return new_artifact_bytes_pair(self.kits, self.out, self.pair_baseline)

    def run_pair(self, specs):
        """Two children, two process groups, one sampler. specs: dicts with name, cmd, cwd, wall_cap, cpu_cap, matcher.
        Returns (pair_rec, [child recs]). Each child gets the unchanged one-worker terminal policy; the pair adds the
        simultaneous-sum RSS stop and the two-kit artifact check."""
        rss_stop = H.FAULTS['rss_stop_bytes'] or H.CAPS['rss_stop_bytes']
        log_max = H.FAULTS['log_max_bytes'] or H.CAPS['log_max_bytes']
        pair = self.register({'step': 'pair:' + '+'.join(s['name'] for s in specs), 'kind': 'pair', 'children': [s['name'] for s in specs],
                              'verdict': 'incomplete', 'reason': 'registered'})
        recs = [self.register({'step': s['name'], 'cmd': s['cmd'], 'cwd': s['cwd'], 'verdict': 'incomplete', 'reason': 'registered',
                               'wall_cap_s': min(s['wall_cap'], self.remaining()), 'cpu_cap_s': s['cpu_cap'], 'pair': pair['step']}) for s in specs]

        def abort(reason, detail=None):
            pair['reason'] = reason; pair['verdict'] = 'UNKNOWN'
            if detail: pair['detail'] = detail
            for r in recs:
                if r['reason'] == 'registered':
                    r['reason'] = reason; r['verdict'] = 'UNKNOWN'
            self.save(); return pair, recs

        if self.remaining() <= 0:
            return abort('stage-deadline')
        try:
            before = H.metrics(self.kit)
        except H.MonitorError as e:
            return abort('monitor-failure', str(e))
        for r in recs: r['metrics_before'] = before
        if H.pressure_bad(before):
            return abort('pressure-before-start')
        logs, procs, pgids, state = [], [], [], []
        t_first = None
        try:
            for s, r in zip(specs, recs):
                logpath = os.path.join(self.out, s['name'] + '.log'); log = open(logpath, 'w'); logs.append((logpath, log))
                t = time.monotonic(); r['started_at'] = time.time(); r['reason'] = 'spawned'
                p = subprocess.Popen(['/usr/bin/time', '-l'] + s['cmd'], cwd=s['cwd'], stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
                procs.append(p); pgids.append(os.getpgid(p.pid))
                state.append({'t_start': t, 'peak_rss': 0, 'peak_members': 0, 'peak_lean': 0, 'live_cpu_peak': 0.0, 'done_at': None, 'reason': None, 'samples': 0})
                t_first = t_first or t
            pair['spawn_skew_s'] = round(state[-1]['t_start'] - state[0]['t_start'], 3)
            pair['pgids_distinct'] = len(set(pgids)) == len(pgids)
            self.save()
            if not pair['pgids_distinct']:
                raise RuntimeError('two children in one process group')
            pair_rss_peak = 0; pair_lean_peak = 0; pair_members_peak = 0; stop_reason = None; stop_child = None; sample_no = 0
            while any(p.poll() is None for p in procs):
                for i, p in enumerate(procs):                       # record exits as they happen
                    if p.poll() is not None and state[i]['done_at'] is None:
                        state[i]['done_at'] = time.monotonic(); state[i]['reason'] = 'completed'
                if all(st['done_at'] is not None for st in state):
                    break
                if H.FAULTS['raise_after'] is not None and sample_no >= H.FAULTS['raise_after']:
                    raise RuntimeError('injected supervisor exception')
                samples = {}
                try:
                    for i, p in enumerate(procs):
                        if p.poll() is None:
                            samples[i] = H.group_sample(pgids[i], sample_no)
                    m = H.metrics(self.kit)
                except H.MonitorError as e:
                    time.sleep(0.2)
                    if all(p.poll() is not None for p in procs):
                        pair['late_sample_error_ignored'] = str(e); continue
                    pair['monitor_error'] = str(e); stop_reason = 'monitor-failure'; break
                sample_no += 1
                sum_rss = 0; sum_lean = 0; sum_members = 0; now = time.monotonic()
                for i, (rss, cpu, n, lean) in samples.items():
                    st = state[i]; st['samples'] += 1
                    st['peak_rss'] = max(st['peak_rss'], rss); st['peak_members'] = max(st['peak_members'], n)
                    st['peak_lean'] = max(st['peak_lean'], lean); st['live_cpu_peak'] = max(st['live_cpu_peak'], cpu)
                    sum_rss += rss; sum_lean += lean; sum_members += n
                    wall = now - st['t_start']
                    logsize = os.path.getsize(logs[i][0]) if os.path.exists(logs[i][0]) else 0
                    if wall > recs[i]['wall_cap_s'] and stop_reason is None: stop_reason, stop_child = 'wall-cap', i
                    if cpu > recs[i]['cpu_cap_s'] and stop_reason is None: stop_reason, stop_child = 'cpu-cap', i
                    if rss > rss_stop and stop_reason is None: stop_reason, stop_child = 'rss-stop', i
                    if logsize > log_max and stop_reason is None: stop_reason, stop_child = 'log-cap', i
                    if lean > 1 and stop_reason is None: stop_reason, stop_child = 'extra-workers', i
                pair_rss_peak = max(pair_rss_peak, sum_rss); pair_lean_peak = max(pair_lean_peak, sum_lean)
                pair_members_peak = max(pair_members_peak, sum_members)
                arts = self.pair_artifacts()
                if stop_reason is None:
                    if sum_rss > rss_stop: stop_reason = 'rss-stop-pair'
                    elif sum_lean > MAX_LEAN_TOTAL: stop_reason = 'extra-workers-pair'
                    elif time.monotonic() > self.deadline: stop_reason = 'stage-deadline'
                    elif H.pressure_bad(m): stop_reason = 'memory-pressure'
                    elif m['swap_used_bytes'] - self.baseline['swap_used_bytes'] > H.CAPS['swap_growth_bytes']: stop_reason = 'swap-growth'
                    elif m['disk_free_bytes'] < H.CAPS['disk_free_min_bytes']: stop_reason = 'disk-low'
                    elif arts > H.CAPS['artifacts_max_bytes']: stop_reason = 'artifact-cap'
                if stop_reason: break
                time.sleep(1.0)
            for i, p in enumerate(procs):
                if p.poll() is not None and state[i]['done_at'] is None:
                    state[i]['done_at'] = time.monotonic(); state[i]['reason'] = 'completed'
        except BaseException as e:
            stop_reason = 'exception'; pair['exception'] = repr(e)
            raise
        finally:
            for i, p in enumerate(procs):
                if p.poll() is None:
                    H.kill_group(pgids[i]); p.wait()
                    state[i]['done_at'] = time.monotonic(); state[i]['reason'] = stop_reason or 'exception'
            for _, log in logs: log.close()
            try:
                after = H.metrics(self.kit)
            except H.MonitorError as e:
                after = 'unavailable: %s' % e
            for i, (s, r) in enumerate(zip(specs, recs)):
                if i >= len(procs):
                    r['reason'] = stop_reason or 'exception'; r['verdict'] = 'UNKNOWN'; continue
                st = state[i]; logpath = logs[i][0]
                text = open(logpath, errors='replace').read() if os.path.exists(logpath) else ''
                r.update({'exit': procs[i].returncode, 'reason': st['reason'], 'wall_s': round(st['done_at'] - st['t_start'], 2),
                          'live_cpu_peak_s': round(st['live_cpu_peak'], 1), 'sampled_group_rss_peak_bytes': st['peak_rss'],
                          'group_members_peak': st['peak_members'], 'lean_processes_peak': st['peak_lean'], 'samples': st['samples'],
                          'log_bytes': len(text), 'log_tail': text[-2000:], 'metrics_after': after, **H.parse_time_l(text)})
                if st['reason'] == 'completed':
                    r['proof_verdict'], r['match_note'] = s['matcher'](procs[i].returncode, text)
                else:
                    r['proof_verdict'] = None
                if stop_reason == 'exception':
                    r['verdict'] = 'UNKNOWN'
                    try:
                        _, _, n_after, _ = H.group_sample(pgids[i])
                        if n_after: H.kill_group(pgids[i])
                        r['group_members_after'] = n_after
                    except H.MonitorError:
                        r['group_members_after'] = None
                else:
                    self.finalize(r, s['cpu_cap'], rss_stop, log_max, pgids[i])
            pair.update({'reason': stop_reason or 'completed', 'stop_child': None if stop_child is None else specs[stop_child]['name'],
                         'pair_rss_peak_bytes': pair_rss_peak, 'pair_lean_peak': pair_lean_peak, 'pair_members_peak': pair_members_peak,
                         'samples': sample_no, 'wall_s': round(max(st['done_at'] for st in state) - t_first, 2) if state and all(st['done_at'] for st in state) else None,
                         'new_artifact_bytes_pair': self.pair_artifacts(), 'metrics_after': after})
            problems = []
            if pair['pair_rss_peak_bytes'] > rss_stop: problems.append('rss-stop-pair-final')
            if pair['new_artifact_bytes_pair'] > H.CAPS['artifacts_max_bytes']: problems.append('artifact-cap-pair-final')
            if pair['pair_lean_peak'] > MAX_LEAN_TOTAL: problems.append('extra-workers-pair-final')
            if isinstance(after, dict) and after['swap_used_bytes'] - self.baseline['swap_used_bytes'] > H.CAPS['swap_growth_bytes']:
                problems.append('swap-growth-pair-final')
            pair['final_problems'] = problems
            verdicts = [r['verdict'] for r in recs]
            if pair['reason'] != 'completed' or problems or 'UNKNOWN' in verdicts or 'incomplete' in verdicts:
                pair['verdict'] = 'UNKNOWN'
                if problems and pair['reason'] == 'completed': pair['reason'] = problems[0]
            elif all(v == 'pass' for v in verdicts):
                pair['verdict'] = 'pass'
            else:
                pair['verdict'] = 'FAIL'
            self.save()
        return pair, recs


