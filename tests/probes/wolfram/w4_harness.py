def clear_target(kit, rel):
    for ext in EXTS:
        p = os.path.join(kit, rel + ext)
        if os.path.exists(p): os.remove(p)


def post_module(r, kit, rel):
    """Fresh-compilation evidence and the cost-miss gate, the same in both modes; a pass without its output is a FAIL."""
    olean = os.path.join(kit, rel + '.olean'); exists = os.path.exists(olean)
    r['olean'] = {'absent_before': r.get('absent_before'), 'exists_after': exists, 'bytes': os.path.getsize(olean) if exists else None,
                  'sha256': H.digest(olean) if exists else None,
                  'mtime_after_start': (os.path.getmtime(olean) >= r.get('started_at', 0) - 1) if exists else None}
    r['fresh_compilation'] = bool(r.get('absent_before') and exists and r['olean']['mtime_after_start'])
    if r['verdict'] == 'pass' and not r['fresh_compilation']:
        r['verdict'] = 'FAIL'; r['reason'] = 'missing-output'
    r['cost_miss'] = H.cost_miss(r) if r['verdict'] == 'pass' else None
    return r


