def clear_target(kit, rel):
    for ext in EXTS:
        p = os.path.join(kit, rel + ext)
        if os.path.exists(p): os.remove(p)


def post_step(r, kit=None, rel=None):
    """The same post-step work in both modes: the deliberate delay knob (controls only), fresh-compilation evidence when
    an output is expected, and the cost-miss gate. A pass without its expected output becomes FAIL (missing-output)."""
    if FAULTS_W4['post_delay_s']: time.sleep(FAULTS_W4['post_delay_s'])
    if rel is not None:
        olean = os.path.join(kit, rel + '.olean'); exists = os.path.exists(olean)
        r['olean'] = {'absent_before': r.get('absent_before'), 'exists_after': exists, 'bytes': os.path.getsize(olean) if exists else None,
                      'sha256': H.digest(olean) if exists else None,
                      'mtime_after_start': (os.path.getmtime(olean) >= r.get('started_at', 0) - 1) if exists else None}
        r['fresh_compilation'] = bool(r.get('absent_before') and exists and r['olean']['mtime_after_start'])
        if r['verdict'] == 'pass' and not r['fresh_compilation']:
            r['verdict'] = 'FAIL'; r['reason'] = 'missing-output'
    r['cost_miss'] = H.cost_miss(r) if r['verdict'] == 'pass' else None
    return r


def run_batch(sup, bname, mode, specs):
    """One batch, S or P, between the same boundaries: t0 before the first target cleanup, t1 after every child's
    post-step and the terminal verdict. specs in order; each has name, cmd, cwd, wall_cap, cpu_cap, matcher and
    optionally kit/rel (an expected output)."""
    b = {'batch': bname, 'mode': mode, 'children': [s['name'] for s in specs], 'pair': None}
    t0 = time.monotonic()
    for s in specs:
        if s.get('rel') is not None:
            clear_target(s['kit'], s['rel']); s['absent_before'] = not os.path.exists(os.path.join(s['kit'], s['rel'] + '.olean'))
    recs = []
    if mode == 'S':
        for s in specs:
            r = sup.run_step(s['name'], s['cmd'], s['cwd'], s['wall_cap'], s['cpu_cap'], s['matcher'])
            r['absent_before'] = s.get('absent_before'); post_step(r, s.get('kit'), s.get('rel')); recs.append(r); sup.save()
            if r['verdict'] != 'pass' or r['cost_miss']:
                b['not_started'] = [pending['name'] for pending in specs[len(recs):]]
                break
        b['verdict'] = 'pass' if all(r['verdict'] == 'pass' for r in recs) else ('UNKNOWN' if any(r['verdict'] == 'UNKNOWN' for r in recs) else 'FAIL')
        b['span_s'] = round(sum(r.get('wall_s') or 0 for r in recs), 2)
    else:
        pair, recs = sup.run_pair(specs)
        for s, r in zip(specs, recs):
            r['absent_before'] = s.get('absent_before'); post_step(r, s.get('kit'), s.get('rel'))
        pair_verdict(pair, recs); sup.save()
        b['verdict'] = pair['verdict']; b['pair'] = pair['step']; b['span_s'] = pair['span_s']
        b['pair_rss_peak_bytes'] = pair['pair_rss_peak_bytes']; b['pair_lean_peak'] = pair['pair_lean_peak']
        b['spawn_skew_s'] = pair['spawn_skew_s']; b['samples'] = pair['samples']; b['ps_reads'] = pair['ps_reads']; b['pair_reason'] = pair['reason']
    b['wall_s'] = round(time.monotonic() - t0, 2)
    b['new_artifact_bytes_pair'] = sup.pair_artifacts()
    b['per_child'] = {r['step']: {k: r.get(k) for k in ('verdict', 'reason', 'wall_s', 'time_l_real_s', 'time_l_user_s', 'time_l_sys_s',
                                                        'time_l_max_rss_bytes', 'sampled_group_rss_peak_bytes', 'cost_miss')}
                      | ({'olean_sha256': r['olean']['sha256']} if 'olean' in r else {}) for r in recs}
    sup.receipts.setdefault('batches', []).append(b); sup.save()
    return b, recs


