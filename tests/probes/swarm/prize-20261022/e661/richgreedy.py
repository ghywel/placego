#!/usr/bin/env python3
"""Rich-norm test for Erdos #661 (bipartite distinct distances).

Idea under test: one centre sees most of a lattice disk through only the 'rich' circles (norms m with large r_2(m)).
Can many centres share this? Allowed norms M_T = {m : r_2(m) >= T} (plus 0). Start with P = Q = lattice disk of radius R,
greedily delete the vertex with the most 'bad' partners (N(p-q) not in M_T), always from the larger side,
until no bad pair is left. Then n = min(|P|,|Q|) (larger side trimmed by greedy order) and D = #distinct N(p-q).
Compare D*sqrt(ln n)/n with the plain lattice disk at the same n.
Time limit built in.
"""
import sys, time, math
import numpy as np

T0 = time.time(); TLIM = 480.0

def r2_table(X):
    r = np.zeros(X + 1, dtype=np.int64)
    a = 0
    while a * a <= X:
        b = np.arange(0, int(math.isqrt(X - a * a)) + 1)
        np.add.at(r, a * a + b * b, 1)
        a += 1
    # r counts (a,b) with a>=0,b>=0; convert to full count over Z^2:
    full = np.zeros(X + 1, dtype=np.int64)
    a = np.arange(-int(math.isqrt(X)), int(math.isqrt(X)) + 1)
    A, B = np.meshgrid(a, a, indexing='ij'); Nn = (A * A + B * B).ravel(); Nn = Nn[Nn <= X]
    np.add.at(full, Nn, 1)
    return full

def disk(R):
    a = np.arange(-R, R + 1)
    A, B = np.meshgrid(a, a, indexing='ij'); A = A.ravel(); B = B.ravel()
    m = A * A + B * B <= R * R
    return A[m], B[m]

def baseline(n):
    # n closest lattice points to 0 vs themselves
    R = int(math.sqrt(n / math.pi)) + 3
    A, B = disk(R)
    N = A * A + B * B; o = np.argsort(N, kind='stable')[:n]
    A = A[o]; B = B[o]
    Nz = (A[:, None] - A[None, :]) ** 2 + (B[:, None] - B[None, :]) ** 2
    return len(np.unique(Nz))

def run(R, T, r2):
    A, B = disk(R)
    n0 = len(A)
    Nz = (A[:, None] - A[None, :]) ** 2 + (B[:, None] - B[None, :]) ** 2   # rows P, cols Q
    allowed = (r2[Nz] >= T) | (Nz == 0)
    bad = ~allowed
    aliveP = np.ones(n0, bool); aliveQ = np.ones(n0, bool)
    degP = bad.sum(1).astype(np.int64); degQ = bad.sum(0).astype(np.int64)
    while True:
        if time.time() - T0 > TLIM:
            return None
        nP = aliveP.sum(); nQ = aliveQ.sum()
        if degP[aliveP].max(initial=0) == 0 and degQ[aliveQ].max(initial=0) == 0:
            break
        side = 'P' if (nP > nQ or (nP == nQ and degP[aliveP].max(initial=0) >= degQ[aliveQ].max(initial=0))) else 'Q'
        if side == 'P':
            d = np.where(aliveP, degP, -1); v = int(np.argmax(d))
            if d[v] <= 0:
                side = 'Q'
            else:
                aliveP[v] = False
                degQ -= bad[v, :]
                continue
        d = np.where(aliveQ, degQ, -1); v = int(np.argmax(d))
        if d[v] <= 0:
            # Q side clean but P not: remove from P
            d = np.where(aliveP, degP, -1); v = int(np.argmax(d)); aliveP[v] = False; degQ -= bad[v, :]
        else:
            aliveQ[v] = False
            degP -= bad[:, v]
    iP = np.nonzero(aliveP)[0]; iQ = np.nonzero(aliveQ)[0]
    n = min(len(iP), len(iQ)); iP = iP[:n]; iQ = iQ[:n]
    sub = Nz[np.ix_(iP, iQ)]
    D = len(np.unique(sub))
    # index of the lattice generated by differences p - q (gcd of 2x2 minors over a sample)
    dA = (A[iP][:, None] - A[iQ][None, :]).ravel(); dB = (B[iP][:, None] - B[iQ][None, :]).ravel()
    rng = np.random.default_rng(0); k = min(len(dA), 400); sel = rng.choice(len(dA), k, replace=False)
    g = 0
    for i in range(k):
        for j in range(i + 1, min(k, i + 40)):
            g = math.gcd(g, int(abs(dA[sel[i]] * dB[sel[j]] - dB[sel[i]] * dA[sel[j]])))
    global LASTIDX; LASTIDX = g
    return n0, n, D

def main():
    R = int(sys.argv[1]) if len(sys.argv) > 1 else 20
    r2 = r2_table(4 * R * R + 10)
    print(f'R={R}  disk points={len(disk(R)[0])}')
    print('T | n0 | n_final | D | D*sqrt(ln n)/n | baseline D at n | baseline ratio')
    Ts = [int(x) for x in sys.argv[2].split(',')] if len(sys.argv) > 2 else [4, 8, 12, 16, 24, 32]
    for T in Ts:
        out = run(R, T, r2)
        if out is None:
            print('TIME LIMIT'); return
        n0, n, D = out
        if n < 3:
            print(T, n0, n, D, 'collapsed'); continue
        b = baseline(n)
        print(f'{T:3d} | {n0} | {n} | {D} | {D*math.sqrt(math.log(n))/n:.4f} | {b} | {b*math.sqrt(math.log(n))/n:.4f} | diff-lattice index {LASTIDX}',
              flush=True)

if __name__ == '__main__':
    main()
